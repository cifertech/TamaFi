void uiDrawIconAt(TFT_eSPI& g, uint8_t id, int x, int y, int size, uint16_t color) {
  if (id >= UI_ICON_COUNT) return;
  int s = size;
  if (s < 16) s = 16;
  if (s > 32) s = 32;
  const uint16_t dim = mix565(color, 0x0000, 0.45f);
  const uint16_t hi = mix565(color, 0xFFFF, 0.55f);
  for (int sy = 0; sy < 16; ++sy) {
    const uint32_t row = kUiIcon[id][sy];
    const int dy = y + (sy * s) / 16;
    int h = y + ((sy + 1) * s) / 16 - dy;
    if (h < 1) h = 1;
    for (int sx = 0; sx < 16; ++sx) {
      const uint8_t p = (uint8_t)((row >> (30 - sx * 2)) & 3u);
      if (!p) continue;
      const int dx = x + (sx * s) / 16;
      int w = x + ((sx + 1) * s) / 16 - dx;
      if (w < 1) w = 1;
      uint16_t c = color;
      if (p == 1) c = dim;
      else if (p == 3) c = hi;
      g.fillRect(dx, dy, w, h, c);
    }
  }
}

static bool iconBounds(uint8_t id, int& x0, int& y0, int& x1, int& y1) {
  x0 = 16;
  y0 = 16;
  x1 = -1;
  y1 = -1;
  if (id >= UI_ICON_COUNT) return false;
  for (int sy = 0; sy < 16; ++sy) {
    const uint32_t row = kUiIcon[id][sy];
    for (int sx = 0; sx < 16; ++sx) {
      if (!((row >> (30 - sx * 2)) & 3u)) continue;
      if (sx < x0) x0 = sx;
      if (sy < y0) y0 = sy;
      if (sx > x1) x1 = sx;
      if (sy > y1) y1 = sy;
    }
  }
  return x1 >= x0 && y1 >= y0;
}

void uiDrawIconCentered(TFT_eSPI& g, uint8_t id, int cx, int cy, int size, uint16_t color) {
  int s = size;
  if (s < 16) s = 16;
  if (s > 32) s = 32;
  int x = cx - s / 2;
  int y = cy - s / 2;
  int x0, y0, x1, y1;
  if (iconBounds(id, x0, y0, x1, y1)) {
    x = cx - ((x0 + x1 + 1) * s + 16) / 32;
    y = cy - ((y0 + y1 + 1) * s + 16) / 32;
  }
  uiDrawIconAt(g, id, x, y, s, color);
}

