static uint16_t mix565(uint16_t a, uint16_t b, float t) {
  if (t < 0.0f) t = 0.0f;
  if (t > 1.0f) t = 1.0f;
  const int r1 = (a >> 11) & 0x1F, g1 = (a >> 5) & 0x3F, b1 = a & 0x1F;
  const int r2 = (b >> 11) & 0x1F, g2 = (b >> 5) & 0x3F, b2 = b & 0x1F;
  return (uint16_t)(((r1 + (int)((r2 - r1) * t)) << 11) |
                    ((g1 + (int)((g2 - g1) * t)) << 5) |
                    (b1 + (int)((b2 - b1) * t)));
}

